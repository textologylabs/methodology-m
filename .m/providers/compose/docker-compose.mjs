const INTEGRATION_TEST_PREAMBLE = `#!/bin/sh
# Topology aliveness probes.
# Generated by compose.render_topology — do not edit by hand.
# Source of truth: project.yaml.

set -eu

# In GitLab DinD, published ports bind on the 'docker' host, not localhost.
# Locally, override by exporting DOCKER_GATEWAY (e.g. DOCKER_GATEWAY=localhost).
DOCKER_GATEWAY="\${DOCKER_GATEWAY:-docker}"
TIMEOUT="\${TIMEOUT:-60}"

check() {
  name="$1"
  url="$2"
  expected="$3"
  elapsed=0
  until response=$(curl -sf "$url" 2>/dev/null) && echo "$response" | grep -q "$expected"; do
    elapsed=$((elapsed + 2))
    if [ "$elapsed" -ge "$TIMEOUT" ]; then
      echo "FAIL: $name — $url did not contain '$expected' within \${TIMEOUT}s"
      return 1
    fi
    sleep 2
  done
  echo "✓ $name"
}
`;

const INTEGRATION_TEST_EPILOGUE = `
echo ""
echo "All topology aliveness probes passed."
`;

function renderIntegrationTest(project) {
  const probeLines = ['', '# Infrastructure baseline — topology aliveness probes'];
  probeLines.push('echo "Infrastructure baseline — topology aliveness probes:"');
  for (const c of project.components) {
    probeLines.push(renderProbeLine(c));
  }
  probeLines.push('');

  return (
    INTEGRATION_TEST_PREAMBLE
    + probeLines.join('\n')
    + INTEGRATION_TEST_EPILOGUE
  );
}

function renderProbeLine(component) {
  const gateway = '${DOCKER_GATEWAY}';
  switch (component.role) {
    case 'frontend-host':
      return `check "${component.name} renders" "http://${gateway}:${component.port}" "app-shell"`;
    case 'frontend':
      return `check "${component.name} remoteEntry.js served" "http://${gateway}:${component.port}/remoteEntry.js" "webpackChunk"`;
    case 'backend':
      return `check "${component.name} health" "http://${gateway}:${component.port}/health" "ok"`;
    default:
      // Unknown role — emit a generic health probe so the script still runs.
      return `check "${component.name} alive" "http://${gateway}:${component.port}/" ""`;
  }
}
